"""
gen_sw_golden.py — Reference classes for the on-board validation mode

Writes sw/vela_app/src/golden_ref.h (VELA-TN-007 §9, VELA-NFR-012): for the
first VELA_GOLDEN_N images of test_batch.bin,
    label      CIFAR-10 label
    golden     class of the float golden model (python/cnn.py)
    expected   class of the bit-exact model of the CNN IP (TN004), i.e. what
               the IP must return for the raw codes of the Python preprocessing
The application compares the class returned by the IP with `golden`
(NFR-012: >= 9 / 10) and reports `expected` mismatches as hardware errors.

Usage:
    python tools/gen_sw_golden.py [output.h]          (make sw-golden)
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "python"), str(ROOT / "verif" / "models")]

import numpy as np                                        # noqa: E402

DATA_DIR = ROOT / "data" / "cifar-10-batches-bin"
WEIGHTS_FILE = ROOT / "data" / "CNN_coeff_3x3.txt"
OUTPUT = ROOT / "sw" / "vela_app" / "src" / "golden_ref.h"
N_IMAGES = 10


def golden_reference(n=N_IMAGES):
    """(labels, golden classes, expected IP classes) of the first n test images."""
    from cnn import cnn_forward
    from cnn_hw_model import emulate_tn004, input_raw
    from data_loader import load_dataset
    from weights_loader import load_weights

    weights = load_weights(str(WEIGHTS_FILE))
    images, labels = load_dataset(str(DATA_DIR), max_images=n)
    golden = [int(cnn_forward(img, weights)[1]) for img in images]
    codes = input_raw(images).astype(np.float64) / 2.0 ** 11     # values seen by the IP
    expected = [int(c) for c in emulate_tn004(codes, weights)["pred"]]
    return [int(v) for v in labels], golden, expected


def header_text(n=N_IMAGES):
    labels, golden, expected = golden_reference(n)

    def row(values):
        return ", ".join(str(v) for v in values)

    return f"""/*
 * golden_ref.h — GENERATED by tools/gen_sw_golden.py (make sw-golden), do not edit
 *
 * First {n} images of test_batch.bin (VELA-TN-007 §9, VELA-NFR-012):
 *   label    : CIFAR-10 label
 *   golden   : class of the float golden model (python/cnn.py)
 *   expected : class of the bit-exact model of the CNN IP (TN004)
 */

#ifndef GOLDEN_REF_H
#define GOLDEN_REF_H

#define VELA_GOLDEN_N {n}

static const unsigned char VELA_GOLDEN_LABEL[VELA_GOLDEN_N]    = {{{row(labels)}}};
static const unsigned char VELA_GOLDEN_CLASS[VELA_GOLDEN_N]    = {{{row(golden)}}};
static const unsigned char VELA_GOLDEN_EXPECTED[VELA_GOLDEN_N] = {{{row(expected)}}};

#endif /* GOLDEN_REF_H */
"""


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUTPUT
    out.write_text(header_text())
    print(f"Wrote {out}")
