"""
gen_weights_header.py — Generate the C++ header holding the CNN weights.

Reads data/CNN_coeff_3x3.txt with python/weights_loader.py (TF layout already
transposed to CHW) and writes a header with one constant array per tensor:

    CONV1_W[64][3][3][3]   CONV1_B[64]
    CONV2_W[32][64][3][3]  CONV2_B[32]
    CONV3_W[20][32][3][3]  CONV3_B[20]
    FC_W[10][180]          FC_B[10]        (FC input in HWC order, like cnn.py)

Values are written with repr(): the shortest decimal that round-trips, so a
double holds exactly the float32 value used by the golden model. The element
type is the macro CNN_WEIGHT_T (default: double), so the same header can be
reused with an HLS fixed-point type.

Usage:
    python tools/gen_weights_header.py [weights.txt] [output.h]
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))

from weights_loader import load_weights   # noqa: E402

TENSORS = ["conv1_w", "conv1_b", "conv2_w", "conv2_b",
           "conv3_w", "conv3_b", "fc_w", "fc_b"]


def c_initializer(array):
    """Nested C initializer list of an N-d array, one innermost row per line."""
    if array.ndim == 1:
        return "{" + ", ".join(repr(float(v)) for v in array) + "}"
    inner = ",\n".join(c_initializer(sub) for sub in array)
    return "{\n" + inner + "\n}"


def generate(weights_path, out_path):
    weights = load_weights(str(weights_path))
    lines = [
        "// cnn_weights.h — GENERATED by tools/gen_weights_header.py, do not edit.",
        f"// Source: {Path(weights_path).name} (TF weights transposed to CHW)",
        "#ifndef CNN_WEIGHTS_H",
        "#define CNN_WEIGHTS_H",
        "",
        "#ifndef CNN_WEIGHT_T",
        "#define CNN_WEIGHT_T double",
        "#endif",
        "",
    ]
    for name in TENSORS:
        arr = weights[name]
        dims = "".join(f"[{d}]" for d in arr.shape)
        lines.append(f"static const CNN_WEIGHT_T {name.upper()}{dims} = {c_initializer(arr)};")
        lines.append("")
    lines.append("#endif // CNN_WEIGHTS_H")
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else ROOT / "data" / "CNN_coeff_3x3.txt"
    dst = sys.argv[2] if len(sys.argv) > 2 else ROOT / "hls" / "generated" / "cnn_weights.h"
    generate(src, dst)
    print(f"Wrote {dst}")
