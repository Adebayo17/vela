static const uint8_t *glyph_rows(char c)
{
    static const uint8_t blank[7] = {0};
    unsigned i;

    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    for (i = 0; i < sizeof(FONT) / sizeof(FONT[0]); i++)
        if (FONT[i].c == c)
            return FONT[i].rows;
    return blank;
}

void vela_text_pixel(volatile uint32_t *disp, int x, int y, uint16_t color)
{
    if (x < VELA_TEXT_X0 || x >= VELA_DISP_W || y < 0 || y >= VELA_DISP_H)
        return;                                    /* outside the text zone */
    disp[y * VELA_DISP_W + x] = color;
}

void vela_text_fill(volatile uint32_t *disp, uint16_t color)
{
    int x, y;
    for (y = 0; y < VELA_DISP_H; y++)
        for (x = VELA_TEXT_X0; x < VELA_DISP_W; x++)
            vela_text_pixel(disp, x, y, color);
}

int vela_text_draw(volatile uint32_t *disp, int x, int y, const char *s,
                   uint16_t fg, uint16_t bg)
{
    for (; *s; s++, x += VELA_CHAR_W) {
        const uint8_t *rows = glyph_rows(*s);
        int r, col;
        for (r = 0; r < VELA_CHAR_H; r++)
            for (col = 0; col < VELA_CHAR_W; col++) {
                int on = r < 7 && col < 5 && ((rows[r] >> (4 - col)) & 1);
                vela_text_pixel(disp, x + col, y + r, on ? fg : bg);
            }
    }
    return x;
}
